// Short share links: https://<viewer>/l/<code> in place of the long
// self-contained /page?token=…, /sensitive?token=… and /secret?token=… links.
//
// A code is nothing but an alias for one signed token. The bridge mints the
// token exactly as before, stores { route, token, exp } under a fresh random
// code, and hands out the short URL; the viewer looks the code up and runs
// the token through the same route handler the long link would have hit.
// Every check the token carried (signature, expiry, route flags, sealed page
// path, the sensitive store's one-time consumption on the bridge) therefore
// applies unchanged, and a code can never do more than its token can.
//
// The store is one small JSON file, written only by the bridge (atomically,
// mode 0600) and read by the viewer. A file rather than a lookup over the
// bridge's loopback API keeps short links working while the bridge restarts,
// just as long links do: the viewer never needed the bridge to serve a page.
// Both services run as the same user with the same .env, so they agree on the
// path (MATRON_SHORT_LINKS_FILE overrides the default in the home directory).

import crypto from 'node:crypto';
import nodeFs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { atomicWriteFileSync } from './atomic-write.js';

// 12 characters from a 62-character alphabet: 62^12 ≈ 2^71.4 possible codes,
// generated by rejection sampling so every character is uniform. Letters and
// digits only, so the code survives linkifiers and markdown that trim a
// trailing '-' or '_'.
export const SHORT_CODE_LENGTH = 12;
const ALPHABET = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789';
const CODE_RE = new RegExp(`^[A-Za-z0-9]{${SHORT_CODE_LENGTH}}$`);

// The routes a code may stand in for. Anything else in the file is ignored.
export const SHORT_LINK_ROUTES = Object.freeze(['view', 'download', 'page', 'secret', 'sensitive', 'sensitive-download']);
const ROUTES = new Set(SHORT_LINK_ROUTES);

// The store prunes expired entries on every write; the cap bounds it even if
// something mints links in a loop (past it, new links go out long).
export const SHORT_LINK_MAX_ENTRIES = 10000;

export function shortLinksFile(env = process.env) {
  return env.MATRON_SHORT_LINKS_FILE || path.join(os.homedir(), '.matron-bridge-short-links.json');
}

// On unless MATRON_SHORT_LINKS is set to off/0/false/no.
export function shortLinksEnabled(env = process.env) {
  const v = String(env.MATRON_SHORT_LINKS ?? '').trim().toLowerCase();
  return !['off', '0', 'false', 'no'].includes(v);
}

export function generateShortCode(randomBytes = crypto.randomBytes) {
  let out = '';
  while (out.length < SHORT_CODE_LENGTH) {
    for (const b of randomBytes(SHORT_CODE_LENGTH * 2)) {
      // 248 = 4 × 62: bytes at or above it would bias the first characters.
      if (b < 248 && out.length < SHORT_CODE_LENGTH) out += ALPHABET[b % 62];
    }
  }
  return out;
}

export function isShortCode(value) {
  return typeof value === 'string' && CODE_RE.test(value);
}

function nowSeconds(now) {
  return Math.floor(now() / 1000);
}

function parseStore(text) {
  try {
    const data = JSON.parse(text);
    if (data && typeof data.links === 'object' && data.links !== null && !Array.isArray(data.links)) return data.links;
  } catch { /* fall through */ }
  return {};
}

function validEntry(entry) {
  return entry
    && typeof entry === 'object'
    && ROUTES.has(entry.r)
    && typeof entry.t === 'string'
    && Number.isFinite(entry.e);
}

// Strict parse for the writer: a store it cannot read is never treated as
// empty and overwritten (that would drop every live code). Only a missing file
// is an empty store; any other read error throws, so the caller hands out the
// long link instead. Unparseable JSON is moved aside, kept for inspection, and
// the store starts over.
function readStoreStrict(fs, file, now) {
  let text;
  try {
    text = fs.readFileSync(file, 'utf8');
  } catch (err) {
    if (err && err.code === 'ENOENT') return {};
    throw err;
  }
  let data;
  try { data = JSON.parse(text); } catch { data = null; }
  if (!data || typeof data.links !== 'object' || data.links === null || Array.isArray(data.links)) {
    const aside = `${file}.corrupt-${now()}`;
    fs.renameSync(file, aside);
    console.warn(`[short-links] store was unreadable, moved it to ${aside} and started a new one`);
    return {};
  }
  return data.links;
}

const LOCK_STALE_MS = 10_000;
const LOCK_WAIT_MS = 2_000;
const LOCK_POLL_MS = 10;

function sleepSync(ms) {
  Atomics.wait(new Int32Array(new SharedArrayBuffer(4)), 0, 0, ms);
}

// An exclusive lock file around each read-modify-write, so two bridge
// processes overlapping a restart cannot each read the same snapshot and have
// the second rename drop the code the first one just handed out. A lock left
// by a crashed process is broken once it is older than LOCK_STALE_MS; a lock
// that cannot be taken in LOCK_WAIT_MS throws (the caller falls back to the
// long link).
function withLock(fs, file, fn) {
  const lock = `${file}.lock`;
  const deadline = Date.now() + LOCK_WAIT_MS;
  let fd;
  for (;;) {
    try {
      fd = fs.openSync(lock, 'wx', 0o600);
      break;
    } catch (err) {
      if (!err || err.code !== 'EEXIST') throw err;
      try {
        if (Date.now() - fs.statSync(lock).mtimeMs > LOCK_STALE_MS) { fs.unlinkSync(lock); continue; }
      } catch (e) {
        if (e && e.code === 'ENOENT') continue;
        throw e;
      }
      if (Date.now() > deadline) throw new Error('short link store is locked');
      sleepSync(LOCK_POLL_MS);
    }
  }
  try {
    return fn();
  } finally {
    try { fs.closeSync(fd); } catch { /* ignore */ }
    try { fs.unlinkSync(lock); } catch { /* ignore */ }
  }
}

// The bridge side: add() mints a code. Every write is a locked
// read-merge-write of the whole store.
export function createShortLinkWriter({ file = shortLinksFile(), now = Date.now, fs = nodeFs, randomBytes = crypto.randomBytes, maxEntries = SHORT_LINK_MAX_ENTRIES } = {}) {
  function live(all) {
    const t = nowSeconds(now);
    const links = {};
    for (const [code, entry] of Object.entries(all)) {
      if (isShortCode(code) && validEntry(entry) && entry.e >= t) links[code] = entry;
    }
    return links;
  }

  function save(links) {
    atomicWriteFileSync(file, JSON.stringify({ version: 1, links }), { fs, mode: 0o600 });
  }

  return {
    // Returns the new code. Throws if the store cannot be read, locked or
    // written, or is full of live codes; callers fall back to the long link.
    // A full store never evicts a live code: each one is a link someone holds.
    add({ route, token, exp }) {
      if (!ROUTES.has(route)) throw new Error(`short link: unsupported route ${route}`);
      if (typeof token !== 'string' || !token) throw new Error('short link: token required');
      if (!Number.isFinite(exp)) throw new Error('short link: exp required');
      return withLock(fs, file, () => {
        const links = live(readStoreStrict(fs, file, now));
        if (Object.keys(links).length >= maxEntries) throw new Error('short link store is full');
        let code;
        do { code = generateShortCode(randomBytes); } while (Object.hasOwn(links, code));
        links[code] = { r: route, t: token, e: exp };
        save(links);
        return code;
      });
    },
    // Drops expired entries (the bridge calls it at startup, so a store left
    // alone between restarts does not keep dead tokens around). Writes only
    // when something was dropped; returns how many were.
    prune() {
      return withLock(fs, file, () => {
        const all = readStoreStrict(fs, file, now);
        const links = live(all);
        const dropped = Object.keys(all).length - Object.keys(links).length;
        if (dropped > 0) save(links);
        return dropped;
      });
    },
  };
}

// The viewer side: resolve() turns a code into { route, token } or null.
// Unknown, malformed, expired and pruned codes all give the same null, so the
// viewer answers each of them exactly as it answers an expired token. The
// parsed file is cached until the file is replaced or touched.
export function createShortLinkReader({ file = shortLinksFile(), now = Date.now, fs = nodeFs } = {}) {
  let cacheKey = null;
  let cache = {};

  function links() {
    let st;
    try { st = fs.statSync(file); } catch { cacheKey = null; cache = {}; return cache; }
    const key = `${st.ino}:${st.size}:${st.mtimeMs}`;
    if (key !== cacheKey) {
      try { cache = parseStore(fs.readFileSync(file, 'utf8')); } catch { cache = {}; }
      cacheKey = key;
    }
    return cache;
  }

  return {
    resolve(code) {
      if (!isShortCode(code)) return null;
      const all = links();
      if (!Object.hasOwn(all, code)) return null;
      const entry = all[code];
      if (!validEntry(entry) || entry.e < nowSeconds(now)) return null;
      return { route: entry.r, token: entry.t };
    },
  };
}

// Bridge helper: turn a long viewer URL (`<base>/<route>?token=<payload>.<sig>`)
// into `<base>/l/<code>`, with the code expiring when the token does. Returns
// the long URL unchanged when the store cannot be written or the URL is not a
// shortenable viewer link, so a short-link failure never costs the user the
// link itself.
export function shortenViewerUrl(writer, longUrl, { log = console } = {}) {
  if (!writer || typeof longUrl !== 'string') return longUrl;
  let u;
  try { u = new URL(longUrl); } catch { return longUrl; }
  const segments = u.pathname.split('/');
  const route = segments.pop();
  const token = u.searchParams.get('token');
  if (!ROUTES.has(route) || !token) return longUrl;
  let exp;
  try {
    exp = JSON.parse(Buffer.from(token.slice(0, token.lastIndexOf('.')), 'base64url').toString('utf8')).exp;
  } catch { return longUrl; }
  if (!Number.isFinite(exp)) return longUrl;
  try {
    const code = writer.add({ route, token, exp });
    return `${u.origin}${segments.join('/')}/l/${code}`;
  } catch (err) {
    log?.warn?.(`[short-links] could not store a short link, handing out the long one: ${err.message}`);
    return longUrl;
  }
}
